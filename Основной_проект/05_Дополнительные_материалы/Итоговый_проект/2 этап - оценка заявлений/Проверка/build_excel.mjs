import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook, SpreadsheetFile, FileBlob} from '@oai/artifact-tool';

const here = path.dirname(fileURLToPath(import.meta.url));
const base = path.dirname(here);
const data = JSON.parse(await fs.readFile(path.join(base,'Пример/Газпром_2023_три_типа.json'),'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('Три типа заявлений');
sheet.showGridLines = false;
sheet.tabColor = '#164B78';
sheet.getRange('A1:H10').format.font = {name:'Arial',size:11,color:'#183044'};
sheet.getRange('A2').values = [['Газпром 2023. Три типа ESG-заявлений']];
sheet.getRange('A2').format.font = {name:'Arial',size:16,bold:true,color:'#164B78'};
sheet.getRange('A2:H2').format.rowHeightPx = 32;
sheet.getRange('A3').values = [['Источник: экологический отчёт Газпрома за 2023 год. '+data.claims[0].source_url.split('#')[0]]];
sheet.getRange('A3').format.font = {name:'Arial',size:10,color:'#365B78'};
sheet.getRange('A3:H3').format.rowHeightPx = 25;
sheet.getRange('A4').values = [['Три выбранных заявления. «Недостаточно данных» означает незавершённую проверку. Декларативность не доказывает гринвошинг.']];
sheet.getRange('A4').format.font = {name:'Arial',size:10,italic:true,color:'#526373'};
sheet.getRange('A4:H4').format.rowHeightPx = 27;
sheet.getRange('A5:H5').values = [['Тип заявления','Дословная цитата','Страница PDF','Печатная страница','Оценка','Основание','Ограничение','ID заявления']];
sheet.getRange('A6:H8').values = data.claims.map(c=>[c.claim_type,c.quote,c.pdf_page,c.printed_page,c.verdict,c.reason,c.limitation,c.claim_id]);
sheet.getRange('A5:H8').format.wrapText = true;
sheet.getRange('A5:H8').format.verticalAlignment = 'top';
sheet.getRange('A5:H5').format = {fill:'#164B78',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},wrapText:true,horizontalAlignment:'center',verticalAlignment:'center'};
sheet.getRange('A5:H5').format.rowHeightPx = 47;
sheet.getRange('A5:H5').format.borders = {insideVertical:{style:'thin',color:'#FFFFFF'}};
for (const [column,width] of Object.entries({A:148,B:500,C:96,D:91,E:164,F:370,G:380,H:220})) sheet.getRange(`${column}5:${column}8`).format.columnWidthPx = width;
for (const row of [6,8]) sheet.getRange(`A${row}:H${row}`).format.fill = '#EAF2F8';
sheet.getRange('A7:H7').format.fill = '#FFFFFF';
sheet.getRange('A6:H6').format.rowHeightPx = 142;
sheet.getRange('A7:H7').format.rowHeightPx = 100;
sheet.getRange('A8:H8').format.rowHeightPx = 86;
sheet.getRange('C6:D8').setNumberFormat('0');
sheet.getRange('C6:D8').format.horizontalAlignment = 'right';
sheet.getRange('E6:E8').format.font = {name:'Arial',size:11,bold:true,color:'#183044'};
sheet.freezePanes.freezeColumns(1);
wb.recalculate();
const inspection = await wb.inspect({kind:'table',sheetId:sheet.name,range:'A5:H8',include:'values,formulas',tableMaxRows:4,tableMaxCols:8,maxChars:5000});
await fs.writeFile(path.join(here,'Excel_проверка.ndjson'),inspection.ndjson);
const preview = await wb.render({sheetName:sheet.name,range:'A1:H9',scale:1,format:'png'});
await fs.writeFile(path.join(here,'Excel_просмотр.png'),new Uint8Array(await preview.arrayBuffer()));
const output = path.join(base,'Пример/Газпром_2023_три_типа.xlsx');
await (await SpreadsheetFile.exportXlsx(wb)).save(output);
const readback = await SpreadsheetFile.importXlsx(await FileBlob.load(output));
const actual = readback.worksheets.getItemAt(0).getRange('A6:H8').values;
const expected = data.claims.map(c=>[c.claim_type,c.quote,c.pdf_page,c.printed_page,c.verdict,c.reason,c.limitation,c.claim_id]);
if (JSON.stringify(actual)!==JSON.stringify(expected)) throw new Error('XLSX readback differs from JSON source');
await fs.writeFile(path.join(here,'Excel_результат.json'),JSON.stringify({status:'verified',rows:3,sheets:1,source:'Газпром_2023_три_типа.json',readback:'all 24 values match',preview:'Excel_просмотр.png'},null,2));
console.log(JSON.stringify({output,rows:actual.length,preview:path.join(here,'Excel_просмотр.png')}));
